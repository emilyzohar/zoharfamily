/* ========================================
   IMAGE GALLERY
======================================== */

function openImageGallery(
  item
) {

  const modal =
    document.getElementById(
      "imageModal"
    );


  const windowElement =
    modal.querySelector(
      ".image-modal-window"
    );


  const image =
    document.getElementById(
      "lightboxImage"
    );


  const files =
    Array.isArray(
      item.file
    )
      ? item.file
      : [
          item.file
        ];


  let currentIndex =
    0;


  let previous =
    document.getElementById(
      "imageGalleryPrev"
    );


  let next =
    document.getElementById(
      "imageGalleryNext"
    );


  if (
    !previous
  ) {

    previous =
      createImageArrow(

        "imageGalleryPrev",

        "image-gallery-arrow image-gallery-arrow-left",

        "‹"

      );


    windowElement.appendChild(
      previous
    );

  }


  if (
    !next
  ) {

    next =
      createImageArrow(

        "imageGalleryNext",

        "image-gallery-arrow image-gallery-arrow-right",

        "›"

      );


    windowElement.appendChild(
      next
    );

  }



  function showImage() {

    image.src =
      files[
        currentIndex
      ];


    image.alt =
      `${item.title || "Image"} ${
        currentIndex +
        1
      }`;


    document.getElementById(
      "lightboxTitle"
    ).textContent =
      item.title ||
      "";


    document.getElementById(
      "lightboxDescription"
    ).textContent =
      `${
        currentIndex +
        1
      } of ${
        files.length
      }`;

  }



  previous.style.display =
    files.length >
    1
      ? "flex"
      : "none";


  next.style.display =
    files.length >
    1
      ? "flex"
      : "none";



  previous.onclick =
    event => {

      event.stopPropagation();


      currentIndex =
        (
          currentIndex -
          1 +
          files.length
        )
        %
        files.length;


      showImage();

    };



  next.onclick =
    event => {

      event.stopPropagation();


      currentIndex =
        (
          currentIndex +
          1
        )
        %
        files.length;


      showImage();

    };



  image.onclick =
    files.length >
    1
      ? next.onclick
      : null;


  showImage();


  openModal(
    modal
  );

}



